#!/usr/bin/env python3
"""Render docs/RESULTS.md from results/results.csv and results/results_extended.csv.

The page is generated so that no number on it can drift away from the committed
evaluation artefacts. Run after scripts/collect_results.py / scripts/reevaluate.py.
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
BLOB = "https://github.com/mtliba/reboot/blob/main/results"
FRACS = [1.0, 0.25, 0.10, 0.05, 0.01]
FRAC_HDR = ["100 %", "25 %", "10 %", "5 %", "1 %"]


def pct(v) -> str:
    return "—" if pd.isna(v) else f"{v:.3f}"


def row(label: str, series: dict, fmt=pct) -> str:
    return "| " + label + " | " + " | ".join(fmt(series.get(f)) for f in FRACS) + " |"


def header() -> str:
    return ("| Model | " + " | ".join(FRAC_HDR) + " |\n|" + "---|" * (len(FRACS) + 1))


def mae_by_frac(df: pd.DataFrame) -> dict:
    return (df.groupby("frac")["mae"].mean() * 100).to_dict()


def std_by_frac(df: pd.DataFrame) -> dict:
    g = df.groupby("frac")["mae"]
    return {f: (s * 100) for f, s in g.std().items()}, {f: int(n) for f, n in g.size().items()}


def main() -> None:
    r = pd.read_csv(ROOT / "results" / "results.csv")
    e = pd.read_csv(ROOT / "results" / "results_extended.csv")
    ind = r[r.protocol == "per_cell_random"]
    out: list[str] = []
    A = out.append

    A("---")
    A("layout: default")
    A("title: Extended results")
    A('description: "All evaluation runs behind the ICASSP tables: four protocols, '
      'three seeds, sweeps, and metrics beyond MAE."')
    A("---\n")
    A("# Extended results\n")
    A("*Generated by `scripts/make_results_page.py` from `results/results.csv` "
      "(%d evaluation runs) and `results/results_extended.csv` (%d runs with the full metric set). "
      "All MAE values are in percentage points of SOC.*\n" % (len(r), len(e)))

    # ---------------- 1. label efficiency, with seed spread -------------------
    A("\n## 1. Label efficiency, with seed spread\n")
    A("Mean over all available repeats; the parenthesised value is the standard deviation across "
      "label subsets and initialisations where more than one run exists. The generic "
      "7-channel encoders are the controlled comparison; the re-implemented published "
      "architectures use their original I, V, T inputs.\n")
    A(header())
    groups = [
        ("ReBoot (Coulomb pairing + mask, 200 ep.)", ind[ind.recipe == "v4 cycle+socproxy+mask"]),
        ("ReBoot (position pairing, 200 ep.)", ind[ind.recipe == "v3 cycle batches"]),
        ("ReBoot (100 ep., ablation reference)", ind[ind.recipe == "ablation:full100"]),
        ("Masked reconstruction only (100 ep.)", ind[ind.recipe == "ablation:maeonly"]),
        ("SimCLR-style (100 ep.)", ind[ind.recipe == "ablation:simclr"]),
        ("Hybrid encoder, from scratch", ind[ind.model == "supervised_hybrid"]),
        ("TCN, from scratch", ind[ind.model == "supervised_tcn"]),
        ("Transformer (generic), from scratch", ind[ind.model == "supervised_transformer"]),
        ("LSTM (generic), from scratch", ind[ind.model == "supervised_lstm"]),
        ("DNN [6], re-implemented", ind[ind.model == "supervised_chemali_dnn"]),
        ("LSTM-RNN [4], re-implemented", ind[ind.model == "supervised_chemali_lstm"]),
        ("GRU-RNN [5], re-implemented", ind[ind.model == "supervised_yang_gru"]),
        ("Transformer [7], re-implemented", ind[ind.model == "supervised_hannan_transformer"]),
        ("CNN-Bi-LSTM-AM [8], re-implemented", ind[ind.model == "supervised_li_cnnbilstm"]),
    ]
    for label, g in groups:
        if g.empty:
            continue
        m = mae_by_frac(g)
        sd, n = std_by_frac(g)
        cells = []
        for f in FRACS:
            if f not in m:
                cells.append("—")
            elif n.get(f, 0) > 1 and not pd.isna(sd.get(f)):
                cells.append(f"{m[f]:.3f} ({sd[f]:.3f})")
            else:
                cells.append(f"{m[f]:.3f}")
        A("| " + label + " | " + " | ".join(cells) + " |")

    A("\n## 2. Raw-input control (encoder sees only I, V, T, Δt)\n")
    A(header())
    A(row("ReBoot (100 ep.)", mae_by_frac(ind[ind.recipe == "ablation:raw"])))
    A(row("Hybrid, from scratch", mae_by_frac(ind[ind.model == "supervised_hybrid_raw"])))
    base = mae_by_frac(ind[ind.model == "supervised_hybrid_raw"])
    reb = mae_by_frac(ind[ind.recipe == "ablation:raw"])
    A("| **relative change** | " + " | ".join(
        f"**{(reb[f] - base[f]) / base[f] * 100:+.0f} %**" if f in base and f in reb else "—"
        for f in FRACS) + " |")
    A("\nPretraining helps at every label fraction once the derived channels are removed from the "
      "encoder input, which is the cleanest statement of its contribution.\n")

    # ---------------- 3. beyond MAE ------------------------------------------
    A("\n## 3. Beyond MAE\n")
    A("In-distribution test split. P95/P99 are percentiles of the absolute error; "
      "`≤1 %` is the fraction of windows predicted within one SOC point.\n")
    A("| Model | labels | MAE | RMSE | P95 | P99 | R² | ≤1 % |\n|---|---|---|---|---|---|---|---|")
    sel = [
        ("ReBoot 200 ep.", "recipe", "v4 cycle+socproxy+mask"),
        ("Masked recon. only", "recipe", "ablation:maeonly"),
        ("SimCLR-style", "recipe", "ablation:simclr"),
        ("Hybrid, from scratch", "model", "supervised_hybrid"),
        ("TCN, from scratch", "model", "supervised_tcn"),
    ]
    ei = e[e.protocol == "per_cell_random"]
    for label, col, val in sel:
        g = ei[ei[col] == val]
        for f, fl in ((1.0, "100 %"), (0.01, "1 %")):
            gg = g[g.frac == f]
            if gg.empty:
                continue
            m = gg.mean(numeric_only=True)
            A(f"| {label} | {fl} | {m.mae*100:.3f} | {m.rmse*100:.3f} | {m.p95*100:.3f} | "
              f"{m.p99*100:.3f} | {m.r2:.4f} | {m.frac_within_1pct*100:.1f} % |")

    # ---------------- 4. ablations -------------------------------------------
    A("\n## 4. Ablations and sweeps (100-epoch pretraining)\n")
    A("| Variant | 100 % | 1 % |\n|---|---|---|")
    abl = [
        ("Full ReBoot, 100 ep.", "ablation:full100"),
        ("− L_refl", "ablation:norefl"),
        ("− L_ord", "ablation:noord"),
        ("− L_phys", "ablation:nophys"),
        ("Single latent", "ablation:single"),
        ("L_mask only", "ablation:maeonly"),
        ("SimCLR-style", "ablation:simclr"),
        ("λ_refl = 0.1 (default 0.5)", "ablation:refl01"),
        ("λ_refl = 2.0", "ablation:refl2"),
        ("λ_phys = 0 ", "ablation:phys0"),
        ("λ_phys = 0.001", "ablation:phys001"),
        ("λ_phys = 0.1", "ablation:phys01"),
        ("λ_phys = 1.0", "ablation:phys1"),
        ("unlabelled pool 10 %", "ablation:pool10"),
        ("unlabelled pool 25 %", "ablation:pool25"),
        ("unlabelled pool 50 %", "ablation:pool50"),
        ("Linear probe (encoder frozen)", "linprobe:v4"),
        ("Full ReBoot, 200 ep.", "v4 cycle+socproxy+mask"),
    ]
    for label, rec in abl:
        g = ind[ind.recipe == rec]
        m = mae_by_frac(g)
        A(f"| {label} | {pct(m.get(1.0))} | {pct(m.get(0.01))} |")
    A("\n`λ_phys` is the clearest knob: the published 0.01 is near optimal at 1 % labels, and "
      "raising it to 1.0 degrades both regimes by a factor of two — the physics term is a weak "
      "constraint, not a second objective. Shrinking the unlabelled pool to 10 % of the cycles "
      "costs more at 1 % labels than at 100 %, as a pretraining effect should.\n")

    # ---------------- 5. distribution shift ----------------------------------
    A("\n## 5. Distribution shift\n")
    A("| Protocol | labels | ReBoot | same encoder, from scratch |\n|---|---|---|---|")
    cb = r[r.protocol == "cross_battery"]
    for f, fl in ((1.0, "100 %"), (0.05, "5 %"), (0.01, "1 %")):
        a = cb[(cb.model == "reboot") & (cb.frac == f)]["mae_pct"].mean()
        b = cb[(cb.model == "supervised_hybrid") & (cb.frac == f)]["mae_pct"].mean()
        A(f"| cross-battery (cells 7, 11, 19 held out) | {fl} | {pct(a)} | {pct(b)} |")
    cc = r[r.protocol == "cross_cycle"]
    a = cc[cc.model == "reboot"]["mae_pct"].mean()
    b = cc[cc.model == "supervised_hybrid"]["mae_pct"].mean()
    A(f"| cross-cycle (final 30 % of each cell's life) | 100 % | {pct(a)} | {pct(b)} |")
    A("\nReBoot neither helps nor hurts materially under shift. The paper reports this as a "
      "limitation rather than a result.\n")

    # ---------------- 6. cost ------------------------------------------------
    A("\n## 6. Model size and inference throughput\n")
    A("| Model | parameters | windows / s (1× A100) |\n|---|---|---|")
    for label, col, val in sel + [("Transformer [7]", "model", "supervised_transformer"),
                                  ("LSTM [4]", "model", "supervised_lstm")]:
        g = ei[ei[col] == val]
        if g.empty:
            continue
        A(f"| {label} | {int(g.n_params.iloc[0]):,} | {g.wps.mean():,.0f} |")
    A("\nReBoot adds no inference cost over the encoder it is built on: pretraining changes the "
      "weights, not the architecture. The decoder and the two projection heads are discarded after "
      "Stage 1.\n")

    A("\n---\n")
    A("Raw artefacts: [`results/results.csv`](%s/results.csv), "
      "[`results/results_extended.csv`](%s/results_extended.csv), "
      "[`results/physics_params.json`](%s/physics_params.json), "
      "[`results/tables/`](%s/tables) (the LaTeX the paper includes verbatim).\n" % ((BLOB,) * 4))

    (ROOT / "docs" / "RESULTS.md").write_text("\n".join(out) + "\n")
    print(f"wrote {ROOT / 'docs' / 'RESULTS.md'} ({len(out)} lines)")


if __name__ == "__main__":
    main()
